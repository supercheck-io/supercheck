import { Command } from 'commander'
import { existsSync, lstatSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { outputDetail } from '../output/formatter.js'
import { CLIError, ExitCode } from '../utils/errors.js'
import { discoverRepository } from '../utils/discover.js'

type Manager = 'npm' | 'pnpm' | 'yarn'

export function githubWorkflow(manager: Manager, usesPlaywright: boolean): string {
  const setupPm = manager === 'pnpm' ? '      - uses: pnpm/action-setup@v4\n' : ''
  const cache = manager
  const install = manager === 'pnpm' ? 'pnpm install --frozen-lockfile' : manager === 'yarn' ? 'yarn install --frozen-lockfile' : 'npm ci'
  const run = manager === 'pnpm' ? 'pnpm exec' : manager === 'yarn' ? 'yarn' : 'npx'
  const browsers = usesPlaywright ? `      - run: ${run} playwright install --with-deps chromium\n` : ''
  return `# Generated by \`supercheck ci init --github\`.
# Pull requests run tests locally on the runner with no Supercheck credentials.
# Pushes to main deploy to Supercheck using repository secrets (see below).
name: Supercheck

on:
  pull_request:
  push:
    branches: [main]
  workflow_dispatch:

permissions:
  contents: read

jobs:
  test:
    if: github.event_name == 'pull_request'
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
${setupPm}      - uses: actions/setup-node@v4
        with:
          node-version: 22
          cache: ${cache}
      - run: ${install}
${browsers}      - run: ${run} supercheck test run --offline --all --json

  deploy:
    if: github.event_name != 'pull_request'
    runs-on: ubuntu-latest
    # Never two deploys at once: they share one supercheck.state.json.
    concurrency:
      group: supercheck-deploy
      cancel-in-progress: false
    env:
      # Create a dedicated CLI token for CI (Dashboard > CLI Tokens) and add it as a repository secret.
      SUPERCHECK_TOKEN: \${{ secrets.SUPERCHECK_TOKEN }}
      # Only needed for self-hosted installs (repository variable).
      SUPERCHECK_URL: \${{ vars.SUPERCHECK_URL }}
    steps:
      - uses: actions/checkout@v4
${setupPm}      - uses: actions/setup-node@v4
        with:
          node-version: 22
          cache: ${cache}
      - run: ${install}
${browsers}      - run: ${run} supercheck deploy --dry-run --json
      - run: ${run} supercheck deploy --force --json --verify
`
}

export const ciCommand = new Command('ci').description('Set up continuous integration')
ciCommand.command('init')
  .description('Write a GitHub Actions workflow (does not create the secrets it needs)')
  .option('--github', 'Generate a GitHub Actions workflow')
  .option('--path <file>', 'Workflow file', '.github/workflows/supercheck.yml')
  .option('--force', 'Replace an existing workflow file')
  .action((options: { github?: boolean; path: string; force?: boolean }) => {
    if (!options.github) throw new CLIError('Specify a provider: supercheck ci init --github', ExitCode.ConfigError)
    const cwd = process.cwd()
    const file = resolve(cwd, options.path)
    if (!file.startsWith(cwd + '/') ) throw new CLIError('Workflow path must be inside the project.', ExitCode.ConfigError)
    for (let current = file; current.length > cwd.length; current = dirname(current)) {
      try { if (lstatSync(current).isSymbolicLink()) throw new CLIError(`Refusing to write through a symlink: ${current}`, ExitCode.ConfigError) } catch (error) { if (error instanceof CLIError) throw error }
    }
    if (existsSync(file) && !options.force) throw new CLIError(`Workflow already exists: ${file}. Use --force to replace it.`, ExitCode.ConfigError)
    const facts = discoverRepository(cwd)
    const manager: Manager = facts.repo.packageManager === 'pnpm' ? 'pnpm' : facts.repo.packageManager === 'yarn' ? 'yarn' : 'npm'
    const usesPlaywright = facts.existingTests.supercheck.playwright > 0 || facts.existingTests.playwright.configs.length > 0 || existsSync(resolve(cwd, '_supercheck_/playwright'))
    mkdirSync(dirname(file), { recursive: true })
    writeFileSync(file, githubWorkflow(manager, usesPlaywright), { flag: options.force ? 'w' : 'wx' })
    outputDetail({
      created: true,
      path: file,
      secretsRequired: [
        { name: 'SUPERCHECK_TOKEN', kind: 'repository secret', note: 'Create a dedicated CLI token in the dashboard; do not reuse an interactive login key.' },
        { name: 'SUPERCHECK_URL', kind: 'repository variable', note: 'Self-hosted installs only.' },
      ],
      reminders: [
        'The workflow file does not create these secrets. A person must add them in the repository settings.',
        'Commit supercheck.state.json so CI updates existing resources rather than creating duplicates. Never commit its .lock file.',
      ],
    })
  })
