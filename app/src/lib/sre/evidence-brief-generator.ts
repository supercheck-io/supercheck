function estimatedConfidence(evidence: BriefEvidenceInput[]) {
  const scores = evidence
    .map((item) => Number(item.confidence))
    .filter((value) => Number.isFinite(value));

  if (scores.length === 0) {
    return evidence.length > 0 ? 0.5 : 0.2;
  }

  return Math.max(
    0,
    Math.min(1, scores.reduce((sum, value) => sum + value, 0) / scores.length),
  );
}

export async function generateEvidenceBrief(input: {
  incidentTitle: string;
  incidentSeverity: string;
  evidence: BriefEvidenceInput[];
  userId: string;
  organizationId: string;
}): Promise<EvidenceBrief> {
  const modelId = getActualModelName();

  if (input.evidence.length === 0) {
    return fallbackBrief([], modelId);
  }

  try {
    validateAIConfiguration();

    const result = await generateText({
      model: getProviderModel(),
      prompt: buildStructuredBriefPrompt(input),
      temperature: 0.1,
      maxRetries: 2,
      maxOutputTokens: 1600,
      abortSignal: AbortSignal.timeout(45_000),
    });

    const parsed = briefSchema.safeParse(JSON.parse(extractJson(result.text)));
    if (!parsed.success) {
      return fallbackBrief(input.evidence, modelId);
    }

    const validIds = new Set(input.evidence.map((item) => item.id));
    return {
      ...parsed.data,
      citedEvidenceIds: parsed.data.citedEvidenceIds.filter((id) =>
        validIds.has(id),
      ),
      provider: "ai",
      modelId,
    };
  } catch (error) {
    console.warn(
      "[SRE Evidence Brief] Falling back to deterministic brief:",
      error,
    );
    return fallbackBrief(input.evidence, modelId);
  }
}

export async function streamEvidenceBrief(
  input: {
    incidentTitle: string;
    incidentSeverity: string;
    evidence: BriefEvidenceInput[];
    userId: string;
    organizationId: string;
  },
  onChunk: (chunk: string) => void | Promise<void>,
): Promise<EvidenceBrief> {
  const modelId = getActualModelName();

  const streamFallback = async (reason?: unknown) => {
    if (reason) {
      console.warn("[SRE Evidence Brief] Streaming fallback:", reason);
    }
    const fallback = fallbackBrief(input.evidence, modelId);
    await onChunk(fallback.summary);
    return fallback;
  };

  if (input.evidence.length === 0) {
    return streamFallback();
  }

  try {
    validateAIConfiguration();

    const result = await streamText({
      model: getProviderModel(),
      prompt: buildStreamingBriefPrompt(input),
      temperature: 0.1,
      maxRetries: 2,
      maxOutputTokens: 1800,
      abortSignal: AbortSignal.timeout(60_000),
    });

    const chunks: string[] = [];
    for await (const chunk of result.textStream) {
      chunks.push(chunk);
      await onChunk(chunk);
    }

    const summary = chunks.join("").trim();
    if (!summary) {
      return streamFallback(new Error("AI provider returned an empty brief"));
    }

    return {
      suspectedFailureDomain: "Native evidence analysis",
      summary,
      confidenceScore: estimatedConfidence(input.evidence),
      citedEvidenceIds: input.evidence.slice(0, 8).map((item) => item.id),
      provider: "ai",
      modelId,
    };
  } catch (error) {
    return streamFallback(error);
  }
}
